namespace Korat.Domain.Auth;

public enum LoginProvider
{
    GitHub = 0,
    Google = 1,
    MagicLink = 2,
    /// <summary>
    /// Провайдер входа Korat (id.korat.*). Личность приходит извне: ProviderUserId — это
    /// его sub, постоянный и переживающий смену почты.
    ///
    /// Значение добавлено, а не заменило существующие: GitHub и Google остаются как
    /// исторические записи привязок, сделанных до переезда, и по ним всё ещё находится
    /// человек. Переиспользовать чужое значение значило бы смешать две разные личности
    /// в одной колонке.
    /// </summary>
    KoratSso = 3,
}
